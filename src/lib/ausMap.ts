/*
  A simplified outline of Australia for the Community Atlas, drawn by the Hub itself: no map tiles, no map
  provider, so nothing about where anyone is goes anywhere. Coastline and borders are rough [longitude, latitude]
  points, good for a country-wide picture and town-level pins, not for navigation.

  The projection is equirectangular, squashed east–west by cos(25°) so the country keeps its familiar shape.
*/

export const MAP_W = 770;
export const MAP_H = 700;
const LNG0 = 112;
const LAT0 = -9.5;
const KX = 20 * Math.cos((25 * Math.PI) / 180);
const KY = 20;

/** A longitude and latitude, as map units (0..MAP_W, 0..MAP_H). */
export const project = (lng: number, lat: number): [number, number] => [(lng - LNG0) * KX, (LAT0 - lat) * KY];

