const d = (ring: Ring, close: boolean) =>
  ring
    .map(
      ([lng, lat], i) =>
        `${i ? "L" : "M"}${project(lng, lat)
          .map((n) => n.toFixed(1))
          .join(" ")}`,
    )
    .join("") + (close ? "Z" : "");

export const LAND_PATH = d(MAINLAND, true) + d(TASMANIA, true);
export const BORDER_PATH = BORDERS.map((b) => d(b, false)).join("");

