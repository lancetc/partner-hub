import "server-only";
import { answerKeysFor, DESIGNATIONS, POOL_KINDS, STATUSES, SURFACES, VIEWS, type PoolContent, type PoolQuery, type VersionStatus } from "@/lib/questionPool";
import { audit, type Db } from "./db";
import { requireAuthor, type User } from "./auth";
import { externalCourses, poolRows, poolUser } from "./questionPool";
import { workbook, type Sheet } from "./xlsx";

/*
  Export Excel: a snapshot of the pool (the current filtered selection, or all of it) as a real workbook. It
  is for review and audits, not for editing: nothing is ever imported back from it. Answer keys are included
  only for reviewers and Hub administrators, the role is checked again here, and every export is logged.
  No learner's name, answers or reflections are in it: only totals per question.
*/

const COVERAGE = {
  unavailable: "External: question list unavailable",
  supplied: "External: question list supplied",
  reconciled: "External: question list manually reconciled",
};
const CREDIT = { correct: "Correct (best answer)", partial: "Part credit (acceptable)", none: "No credit" };

export function exportPool(db: Db, user: User, query: PoolQuery, opts: { keys: boolean; versions: boolean }, now: Date) {
  requireAuthor(user);
  // The role is checked now, not when the page was loaded.
  const keys = opts.keys && answerKeysFor(poolUser(db, user));
  const { rows, total } = poolRows(db, query, now);
  const ids = rows.map((r) => r.id);
  const inIds = (sql: string) => {
    const out: Record<string, unknown>[] = [];
    for (let i = 0; i < ids.length; i += 400) {
      const part = ids.slice(i, i + 400);
      out.push(...(db.prepare(sql.replace("(?)", `(${part.map(() => "?").join(",")})`)).all(...part) as Record<string, unknown>[]));
    }
    return out;
  };
  const versions = inIds(
    "SELECT v.*, u.name AS approver FROM pool_versions v LEFT JOIN users u ON u.id = v.approved_by WHERE v.question_id IN (?) ORDER BY v.question_id, v.version",
  ) as {
    question_id: string;
    version: number;
    status: VersionStatus;
    kind: keyof typeof POOL_KINDS;
    content: string;
    migrated: number;
    created_at: string;
    approved_by: string | null;
    approver: string | null;
    approved_at: string | null;
  }[];
  const byQ = new Map<string, typeof versions>();
  for (const v of versions) byQ.set(v.question_id, [...(byQ.get(v.question_id) ?? []), v]);
  const filters = Object.entries(query)
    .filter(([k, v]) => v && !["page", "sort", "dir"].includes(k))
    .map(([k, v]) => (k === "view" ? `view: ${VIEWS.find((x) => x.id === v)?.label ?? v}` : `${k}: ${v}`));
  const stamp = now.toISOString();
  const scope = filters.length ? `The filtered selection (${filters.join("; ")})` : "The whole Question Pool";

  const readMe: Sheet = {
    name: "Read me",
    header: ["Item", "Detail"],
    widths: [34, 110],
    rows: [
      [
        "What this is",
        "A point-in-time snapshot of the Trilogy Care Partner Hub Question Pool. It is not a way to edit questions: changes are made in the Hub and reviewed there.",
      ],
      ["Classification", keys ? "CONFIDENTIAL: contains assessment answers. Do not share with learners." : "Inventory only: no answer keys in this file."],
      ["Scope", scope],
      ["Sorted by", `${query.sort ?? "id"} ${query.dir === "desc" ? "descending" : "ascending"}`],
      ["Generated (UTC)", stamp],
      ["Generated by", user.name],
      ["Questions in this file", String(total)],
      ["Version rows", opts.versions ? "Every version of each question" : "The current version of each question"],
      ["Learner data", "None. No learner names, answers, attempts or reflections are exported: only totals per question."],
      ["", ""],
      ["Sheet: Questions", "One row per question (or per version). ID is stable for the life of the question. Live uses counts places it is published now."],
      [
        "Sheet: Options and feedback",
        keys
          ? "One row per answer option, with its credit and feedback, then any general feedback and explanation."
          : "Not included: answer keys are for reviewers and Hub administrators.",
      ],
      ["Sheet: Placements", "One row per use of a question version: where, in which release, published or draft, current or historical."],
      ["Sheet: Review history", "Each review action: who, when, from and to which status."],
      [
        "Sheet: External SCORM",
        "Imported packages. The Hub cannot see inside a package: a question count is shown only where a list was supplied or reconciled.",
      ],
      ["", ""],
      ...Object.entries(STATUSES).map(([, s]) => [`Status: ${s.label}`, s.meaning]),
      ["First review due", "Approved when the pool was set up because it was already live with learners; not yet reviewed in the pool."],
      ["Formulas", "Every cell is text. Text that begins with =, +, - or @ has an apostrophe put in front so it can never run as a formula."],
    ],
  };

  const questions: Sheet = {
    name: "Questions",
    header: [
      "ID",
      "Title",
      "Version",
      "Question",
      "Type",
      "Topic",
      "Skill tested",
      "Audience",
      "Programme",
      "Intended use",
      "Status",
      "Risk",
      "Owner",
      "Approved version",
      "Approved by",
      "Approved (UTC)",
      "First review due",
      "Next review",
      "Review trigger",
      "Source",
      "Source location",
      "Source status",
      "Live uses",
      "All uses",
      "Used in",
      "Live without approval",
      "Possible duplicate",
      "Last attempted (UTC)",
      "First answers (assessed)",
      "First answers (knowledge check)",
      "First answers (practice)",
      "Tags",
    ],
    widths: [10, 36, 8, 60, 20, 26, 26, 20, 16, 16, 14, 10, 18, 10, 20, 22, 10, 12, 26, 30, 26, 12, 8, 8, 30, 10, 10, 22, 18, 18, 18, 20],
    rows: rows.flatMap((r) => {
      const all = byQ.get(r.id) ?? [];
      const approved = all.find((v) => v.version === r.approvedVersion);
      const signal = (d: string) => {
        const s = r.signals.find((x) => x.designation === d);
        return s ? `${s.correct} of ${s.attempts} right` : "";
      };
      const line = (v: (typeof all)[number] | undefined) => [
        r.id,
        r.title,
        v ? `v${v.version}` : `v${r.currentVersion}`,
        v ? (JSON.parse(v.content) as PoolContent).stem : r.stem,
        POOL_KINDS[v?.kind ?? r.kind],
        r.topic,
        r.skill,
        r.audience,
        r.programme,
        r.intendedUse,
        STATUSES[v?.status ?? r.status].label,
        r.risk === "high" ? "High" : "Standard",
        r.owner?.name ?? "",
        r.approvedVersion ? `v${r.approvedVersion}` : "",
        approved ? (approved.approver ?? approved.approved_by ?? (approved.migrated ? "Recorded at set-up (already live)" : "")) : "",
        r.approvedAt ?? "",
        r.unreviewed ? "Yes" : "",
        r.nextReview ?? "",
        r.reviewTrigger,
        r.source?.title ?? "",
        r.sourceRef,
        r.source ? (r.source.superseded ? "Superseded" : "Current") : "",
        String(r.liveUses),
        String(r.totalUses),
        r.surfaces.map((s) => SURFACES[s]).join(", "),
        r.liveUnapproved ? "Yes" : "",
        r.duplicate ? "Yes" : "",
        r.lastAttempt ?? "",
        signal("assessed"),
        signal("formative"),
        signal("practice"),
        r.tags.join(", "),
      ];
      return opts.versions ? all.map(line) : [line(all.find((v) => v.version === r.currentVersion))];
    }),
  };

  const options: Sheet = {
    name: "Options and feedback",
    header: ["Question ID", "Version", "Order", "Answer option", "Credit", "Feedback"],
    widths: [12, 8, 8, 60, 22, 70],
    rows: keys
      ? rows.flatMap((r) =>
          (byQ.get(r.id) ?? [])
            .filter((v) => opts.versions || v.version === r.currentVersion)
            .flatMap((v) => {
              const c = JSON.parse(v.content) as PoolContent;
              return [
                ...c.options.map((o, i) => [r.id, `v${v.version}`, String(i + 1), o.text, CREDIT[o.credit], o.feedback ?? ""]),
                ...(c.feedback?.correct ? [[r.id, `v${v.version}`, "", "(Any correct answer)", "", c.feedback.correct]] : []),
                ...(c.feedback?.incorrect ? [[r.id, `v${v.version}`, "", "(Any other answer)", "", c.feedback.incorrect]] : []),
                ...(c.explanation ? [[r.id, `v${v.version}`, "", "(Explanation)", "", c.explanation]] : []),
              ];
            }),
        )
      : [["", "", "", "Answer keys are not included in this export.", "", ""]],
  };

  const placements: Sheet = {
    name: "Placements",
    header: [
      "Question ID",
      "Version",
      "Used as",
      "Formal or practice",
      "Course or Topic ID",
      "Course or Topic",
      "Where in it",
      "Release",
      "Published or draft",
      "Current or historical",
      "First seen (UTC)",
      "Last seen (UTC)",
    ],
    widths: [12, 8, 22, 18, 30, 40, 30, 14, 14, 14, 22, 22],
    rows: (
      inIds("SELECT * FROM pool_placements WHERE question_id IN (?) ORDER BY question_id, current DESC, last_seen DESC") as {
        question_id: string;
        version: number;
        surface: keyof typeof SURFACES;
        designation: keyof typeof DESIGNATIONS;
        container_id: string;
        container_title: string;
        location_title: string;
        release: string;
        live: number;
        current: number;
        first_seen: string;
        last_seen: string;
      }[]
    ).map((p) => [
      p.question_id,
      `v${p.version}`,
      SURFACES[p.surface],
      DESIGNATIONS[p.designation],
      p.container_id,
      p.container_title,
      p.location_title,
      p.release,
      p.live ? "Published" : "Draft",
      p.current ? "Current" : "Historical",
      p.first_seen,
      p.last_seen,
    ]),
  };

  const history: Sheet = {
    name: "Review history",
    header: ["Question ID", "Version", "Action", "From", "To", "By", "Note", "When (UTC)"],
    widths: [12, 8, 20, 14, 14, 22, 80, 22],
    rows: (
      inIds("SELECT e.*, u.name FROM pool_review_events e LEFT JOIN users u ON u.id = e.actor WHERE e.question_id IN (?) ORDER BY e.question_id, e.id") as {
        question_id: string;
        version: number | null;
        action: string;
        from_status: string | null;
        to_status: string | null;
        name: string | null;
        note: string;
        at: string;
      }[]
    ).map((e) => [
      e.question_id,
      e.version ? `v${e.version}` : "",
      e.action.replace(/_/g, " "),
      e.from_status ?? "",
      e.to_status ?? "",
      e.name ?? "The Hub",
      e.note,
      e.at,
    ]),
  };

  const scorm: Sheet = {
    name: "External SCORM",
    header: [
      "Course ID",
      "Title",
      "Status",
      "Standard",
      "Package file",
      "Uploaded (UTC)",
      "Uploaded by",
      "Owner",
      "Has an assessment",
      "Question coverage",
      "Verified question count",
      "Review date",
      "Note",
    ],
    widths: [24, 40, 12, 12, 34, 22, 20, 20, 14, 40, 12, 12, 60],
    rows: externalCourses(db).map((c) => [
      c.id,
      c.title,
      c.status,
      c.standard,
      c.file,
      c.uploadedAt,
      c.uploadedBy,
      c.owner,
      c.hasAssessment === "unknown" ? "Not known" : c.hasAssessment === "yes" ? "Yes" : "No",
      COVERAGE[c.coverage],
      c.coverage !== "unavailable" && c.questionCount != null ? String(c.questionCount) : "",
      c.reviewDate ?? "",
      c.note,
    ]),
  };

  audit(db, {
    actor: user.id,
    event: "pool.exported",
    entity: "question_pool",
    next: { scope: filters.length ? filters : "all", questions: total, answerKeys: keys, versions: opts.versions },
    at: now,
  });
  return {
    buffer: workbook([readMe, questions, options, placements, history, scorm]),
    filename: `Question Pool ${stamp.slice(0, 10)}${keys ? " CONFIDENTIAL answer keys" : ""}.xlsx`,
    keys,
    total,
  };
}
